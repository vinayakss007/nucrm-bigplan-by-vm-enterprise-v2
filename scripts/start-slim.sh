#!/usr/bin/env bash
set -euo pipefail

# ═══════════════════════════════════════════════════════════════
# NuCRM — Slim Start (low-RAM: Codespaces / small VMs / laptops)
# One command: slim infra (pg+redis) → migrate → start app
#
# RAM budget: ~500-600MB total
#   postgres ~100MB | redis ~20MB | next start ~300-400MB (512MB heap cap)
#
# Skipped on purpose (saves ~3GB): worker, realtime, pgbouncer, minio,
# monitoring stack. See docker-compose.slim.yml header for details.
#
# Usage:
#   bash scripts/start-slim.sh              # dev server (default: instant, no build)
#   bash scripts/start-slim.sh --prod       # prod server (needs `next build` first)
#   bash scripts/start-slim.sh --prod --build  # build (SLIM_BUILD=1, slow) + prod start
#   bash scripts/start-slim.sh --seed       # also run dev seed
#   PORT=3001 bash scripts/start-slim.sh    # custom port
# ═══════════════════════════════════════════════════════════════

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
APP_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$APP_DIR"

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; CYAN='\033[0;36m'; NC='\033[0m'
info() { echo -e "${CYAN}[slim]${NC} $1"; }
ok()   { echo -e "${GREEN}[slim]${NC} $1"; }
warn() { echo -e "${YELLOW}[slim]${NC} $1"; }
fail() { echo -e "${RED}[slim]${NC} $1"; }

BUILD=0; SEED=0; PROD=0
for arg in "$@"; do
  case "$arg" in
    --build) BUILD=1 ;;
    --seed)  SEED=1 ;;
    --prod)  PROD=1 ;;
    -h|--help) sed -n '2,22p' "$0"; exit 0 ;;
    *) fail "Unknown flag: $arg (see --help)"; exit 1 ;;
  esac
done

PORT="${PORT:-3000}"
export POSTGRES_DB="${POSTGRES_DB:-nucrm}"
export POSTGRES_USER="${POSTGRES_USER:-nucrm}"
export POSTGRES_PORT="${POSTGRES_PORT:-5432}"
export REDIS_PORT="${REDIS_PORT:-6379}"

# ─── Step 0: .env.local (generate slim defaults if missing) ───
if [ ! -f "$APP_DIR/.env.local" ] && [ ! -f "$APP_DIR/.env" ]; then
  info "No .env.local found — generating slim defaults (random secrets)..."
  gen() { node -e "console.log(require('crypto').randomBytes($1).toString('base64'))"; }
  POSTGRES_PASSWORD="$(node -e "console.log(require('crypto').randomBytes(12).toString('hex'))")"
  cat > "$APP_DIR/.env.local" <<EOF
# Generated by scripts/start-slim.sh — LOCAL SLIM ONLY, do not reuse in prod
DATABASE_URL=postgresql://${POSTGRES_USER}:${POSTGRES_PASSWORD}@localhost:${POSTGRES_PORT}/${POSTGRES_DB}
DATABASE_SSL=false
DATABASE_POOL_SIZE=5
REDIS_URL=redis://localhost:${REDIS_PORT}
POSTGRES_DB=${POSTGRES_DB}
POSTGRES_USER=${POSTGRES_USER}
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_PORT=${POSTGRES_PORT}
REDIS_PORT=${REDIS_PORT}
JWT_SECRET=$(gen 48)
SESSION_SECRET=$(gen 32)
SETUP_KEY=$(node -e "console.log(require('crypto').randomBytes(32).toString('hex'))")
CRON_SECRET=$(gen 48)
ENCRYPTION_KEY=$(node -e "console.log(require('crypto').randomBytes(32).toString('hex'))")
NEXT_PUBLIC_APP_URL=http://localhost:${PORT}
ALLOWED_ORIGINS=http://localhost:${PORT}
NODE_ENV=production
NEXT_TELEMETRY_DISABLED=1
SENTRY_DISABLE=true
EOF
  ok ".env.local created (slim defaults)"
fi
if [ -f "$APP_DIR/.env.local" ]; then
  set -a; source "$APP_DIR/.env.local"; set +a
elif [ -f "$APP_DIR/.env" ]; then
  set -a; source "$APP_DIR/.env"; set +a
fi
# Slim overrides: local Puzzle, no SSL, no telemetry — always win over file values.
export DATABASE_URL="postgresql://${POSTGRES_USER:-nucrm}:${POSTGRES_PASSWORD:-nucrm}@localhost:${POSTGRES_PORT:-5432}/${POSTGRES_DB:-nucrm}"
export REDIS_URL="redis://localhost:${REDIS_PORT:-6379}"
export DATABASE_SSL="false"
export NEXT_TELEMETRY_DISABLED=1
export SENTRY_DISABLE=true
if [ "$PROD" = "1" ]; then
  export NODE_ENV=production
  # Small heap for low RAM.
  export NODE_OPTIONS="--max-old-space-size=512 ${NODE_OPTIONS:-}"
else
  # Dev mode: instant start, no build needed; 768MB heap is enough.
  export NODE_ENV=development
  export NODE_OPTIONS="--max-old-space-size=768 ${NODE_OPTIONS:-}"
fi

# ─── Step 1: slim infra (postgres + redis only) ───
info "Starting slim infra (postgres + redis, ~120MB)..."
docker compose -f docker-compose.slim.yml up -d
info "Waiting for postgres + redis to be healthy..."
for _ in $(seq 1 30); do
  PG_OK=$(docker inspect --format='{{.State.Health.Status}}' nucrm-db-slim 2>/dev/null || echo starting)
  RD_OK=$(docker inspect --format='{{.State.Health.Status}}' nucrm-redis-slim 2>/dev/null || echo starting)
  if [ "$PG_OK" = "healthy" ] && [ "$RD_OK" = "healthy" ]; then break; fi
  sleep 2
done
PG_OK=$(docker inspect --format='{{.State.Health.Status}}' nucrm-db-slim 2>/dev/null || echo unknown)
RD_OK=$(docker inspect --format='{{.State.Health.Status}}' nucrm-redis-slim 2>/dev/null || echo unknown)
if [ "$PG_OK" != "healthy" ] || [ "$RD_OK" != "healthy" ]; then
  fail "Infra not healthy (pg=$PG_OK redis=$RD_OK). Logs:"
  docker compose -f docker-compose.slim.yml logs --tail=20
  exit 1
fi
ok "Infra healthy (pg=$PG_OK redis=$RD_OK)"
docker stats --no-stream --format 'table {{.Name}}\t{{.MemUsage}}\t{{.MemPerc}}' nucrm-db-slim nucrm-redis-slim || true

# ─── Step 2: migrations (idempotent) ───
info "Applying migrations..."
npx tsx scripts/migrate.ts --yes < /dev/null
ok "Migrations complete"

# ─── Step 3: optional seed ───
if [ "$SEED" = "1" ]; then
  info "Seeding dev data..."
  npx tsx scripts/seed-dev.ts || warn "Seed failed — continuing without seed data"
  ok "Seed step done"
fi

# ─── Step 4: build (prod mode only, only if needed / forced) ───
# NOTE: `next build` needs ~2GB+ heap and several minutes; on tiny boxes it may
# be killed mid-compile. If so, build once on a bigger machine/CI and copy
# .next over, or just run slim in dev mode (default).
if [ "$PROD" = "1" ]; then
  if [ "$BUILD" = "1" ] || { [ ! -f ".next/BUILD_ID" ] && [ ! -f ".next/build-manifest.json" ]; }; then
    info "Building (SLIM_BUILD=1: single-worker, low RAM, slower)..."
    SLIM_BUILD=1 NODE_OPTIONS="--max-old-space-size=2048" npm run build
    ok "Build complete"
  else
    info "Reusing existing .next build (--build to force)"
  fi
fi

# ─── Step 5: start app (foreground) ───
echo ""
if [ "$PROD" = "1" ]; then
  ok "Slim stack ready → http://localhost:${PORT} (prod, heap capped at 512MB)"
  warn "Slim mode: worker/realtime/minio/monitoring are OFF (see docker-compose.slim.yml)"
  echo ""
  exec node --max-old-space-size=512 node_modules/next/dist/bin/next start -p "$PORT"
else
  ok "Slim stack ready → http://localhost:${PORT} (dev, heap capped at 768MB)"
  warn "Slim mode: worker/realtime/minio/monitoring are OFF (see docker-compose.slim.yml)"
  echo ""
  exec node --max-old-space-size=768 node_modules/next/dist/bin/next dev -p "$PORT"
fi
