/**
 * HTML escape utility for email template variable interpolation.
 * Prevents XSS / HTML injection when user-supplied values are injected into HTML templates.
 */

export function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
